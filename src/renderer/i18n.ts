/**
 * UI strings: French literals are the keys (the source language), English is a table.
 * `t('Texte {n}', { n })` interpolates. Language: settings.language (system | fr | en).
 */
let lang: 'fr' | 'en' = 'fr'

export function setLanguage(setting: 'system' | 'fr' | 'en') {
  lang = setting === 'system' ? (navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en') : setting
}
export function currentLanguage() { return lang }

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = lang === 'en' ? (EN[key] ?? key) : key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

